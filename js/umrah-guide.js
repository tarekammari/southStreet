class UmrahEngine {
  constructor() {
    this.currentMode = 'tawaf'; // 'tawaf' or 'sai'
    this.count = 0;
  }

  setMode(mode) {
    this.currentMode = mode;
    this.count = 0;
    this.updateUI();
  }

  incrementCounter() {
    if (this.count < 7) {
      this.count++;
      this.triggerHapticFeedback();
      this.updateUI();
    }
  }

  resetCounter() {
    this.count = 0;
    this.updateUI();
  }

  triggerHapticFeedback() {
    if (navigator.vibrate) {
      navigator.vibrate([60, 40, 60]);
    }
    window.chatEngine?.playAudioTone(900, 0.08);
  }

  updateUI() {
    const numEl = document.getElementById('umrah-counter-number');
    const labelEl = document.getElementById('umrah-counter-label');
    const duaEl = document.getElementById('umrah-dua-text');

    if (numEl) numEl.textContent = this.count;
    if (labelEl) {
      labelEl.textContent = this.currentMode === 'tawaf' 
        ? `الشوط ${this.count} من 7 (الطواف)` 
        : `الشوط ${this.count} من 7 (السعي)`;
    }

    if (duaEl) {
      const duasList = RITUAL_DUAS[this.currentMode];
      if (this.count > 0 && this.count <= 7) {
        duaEl.textContent = duasList[this.count - 1];
      } else {
        duaEl.textContent = 'اضغط على قرص العداد بيدك لتسجيل الشوط وسماع دعاء الشوط المباشر.';
      }
    }
  }
}

window.umrahEngine = new UmrahEngine();
